async function generateSiteStub({ brief = "", kind = "build" } = {}) {
  const validateBundle = validator();
  const title = "MITEX AI Site";
  const files = [
    { path: "index.html", content: genHtml({ title }) },
    { path: "about.html", content: genAbout() },
    { path: "contact.html", content: genContact() },
    { path: "styles.css", content: genCss() },
    { path: "app.js", content: genJs() },
    { path: "README.md", content: `# MITEX AI Generated Site\n\nGenerated in stub mode from brief:\n\n${brief.slice(0, 200)}` },
  ];
  const checked = validateBundle(files);
  if (!checked.ok) {
    const err = new Error(`Stub bundle failed validation: ${checked.errors.join("; ")}`);
    err.code = "VALIDATION_FAILED";
    throw err;
  }
  return {
    ok: true,
    files: checked.files,
    errors: [],
    warnings: checked.warnings,
    summary: kind === "fix" ? "Applied safe placeholder fixes (stub mode)" : "Built a clean placeholder site (stub mode)",
    notes: "This is generated in AI_STUB mode. Real copy, logo and images still need to be supplied.",
    usage: { inputTokens: 0, outputTokens: 0 },
    model: "stub/mitex-ai",
  };
}

