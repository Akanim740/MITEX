function detectLocale(countryCode) {
  return LANG_BY_COUNTRY[countryCode] || "en";
}

let currentLocale = localStorage.getItem("mitex_locale") || "en";
let currentCountry = localStorage.getItem("mitex_country") || detectCountry();

function setLocale(locale) {
  if (!I18N[locale]) locale = "en";
  currentLocale = locale;
  localStorage.setItem("mitex_locale", locale);
  applyTranslations();
}

function setCountry(cc) {
  currentCountry = cc;
  localStorage.setItem("mitex_country", cc);
  const newLocale = detectLocale(cc);
  if (newLocale !== currentLocale) setLocale(newLocale);
  updatePriceDisplays();
}

function t(key) {
  return (I18N[currentLocale] && I18N[currentLocale][key])
    || (I18N.en && I18N.en[key])
    || key;
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    el.title = t(key);
  });
  document.documentElement.lang = currentLocale;
}

function updatePriceDisplays() {
  document.querySelectorAll("[data-price-ngn]").forEach((el) => {
    const ngN = Number(el.getAttribute("data-price-ngn"));
    el.textContent = formatPriceWithOriginal(ngN, currentCountry);
  });
}
